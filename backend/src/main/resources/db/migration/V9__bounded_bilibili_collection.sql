-- 文件职责：持久化有界 B站 URL 采集批次；原始资料、旧快照和分析记录均不改写。
CREATE TABLE source_collection_batch (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  workspace_scope VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  platform VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  canonical_url VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  requested_source_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  resolved_bvid VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
  resolved_aid VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
  requested_root_limit INT NOT NULL,
  include_replies TINYINT(1) NOT NULL DEFAULT 1,
  status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  completeness VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
  source_reported_comments INT NULL,
  collected_root_count INT NULL,
  collected_comment_count INT NULL,
  partial_thread_count INT NULL,
  snapshot_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  import_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  storage_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  tool_name VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  tool_version VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  recoveries INT NOT NULL DEFAULT 0,
  owner_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  lease_until DATETIME(6) NULL,
  last_error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  started_at DATETIME(6) NULL,
  finished_at DATETIME(6) NULL,
  UNIQUE KEY uk_collection_request (workspace_scope, project_id, request_key),
  KEY ix_collection_dispatch (status, lease_until, created_at),
  KEY ix_collection_project (project_id, created_at, id),
  CONSTRAINT fk_collection_project FOREIGN KEY (project_id) REFERENCES business_project(id),
  CONSTRAINT fk_collection_snapshot FOREIGN KEY (snapshot_id) REFERENCES data_snapshot(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
